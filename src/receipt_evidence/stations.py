_PLACE = {name: city for city, names in _CITY.items() for name in names}

def _normalize(name: str) -> str:
    s = unicodedata.normalize("NFC", name)
    s = re.sub(r"\(.*?\)|\[.*?\]", "", s)
    s = re.sub(r"\s+", "", s)
    s = re.sub(r"^(KTX|SRT|ITX)[-·]?", "", s, flags=re.I)
    for suffix in ("종합버스터미널", "고속버스터미널", "시외버스터미널", "버스터미널", "터미널", "국제공항", "역"):
        if s.endswith(suffix) and len(s) > len(suffix):
            s = s[: -len(suffix)] + ("공항" if suffix == "국제공항" else "")
            break
    return s

def city_name(name: str | None) -> str:
    """비교용 도시 이름: 역·공항이면 그 도시, 아니면 '나주시'→'나주'처럼 시·군·구를 뗀 이름."""
    if not name or not name.strip():
        return ""
    s = unicodedata.normalize("NFC", name).strip()
    city = place_of(s)
    if city:
        return city
    s = re.sub(r"\s+", "", s)
    return s[:-1] if len(s) > 2 and s[-1] in "시군구" else s

def place_of(name: str | None) -> str | None:
    """역·터미널·공항 이름의 도시. 모르면 None."""
    if not name or not name.strip():
        return None
    s = _normalize(name)
    return _PLACE.get(s) or (_PLACE.get(s + "공항") if not s.endswith("공항") else _PLACE.get(s[:-2]))
